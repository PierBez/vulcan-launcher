#!/usr/bin/env python3
"""Export Vulcan's sunset from the Android vectors. Requires Pillow.

Run from any directory: python3 tools/export-logo.py
The two Android drawable XML files are the source for every exported logo.
"""

import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw, PngImagePlugin

ROOT = Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / "app/src/main/res/drawable"
ANDROID = "{http://schemas.android.com/apk/res/android}"
ORIGIN = (
    "Origin: Vulcan's authored sunset vectors in "
    "app/src/main/res/drawable/ic_launcher_foreground.xml and "
    "ic_launcher_background.xml, exported by tools/export-logo.py using Pillow. "
    "The central 72/108 adaptive-layer crop matches Android. No generated or sourced artwork."
)


def main():
    foreground = ET.parse(DRAWABLE / "ic_launcher_foreground.xml").getroot()
    background = ET.parse(DRAWABLE / "ic_launcher_background.xml").getroot()
    sun, horizon = foreground.findall("path")
    attr = lambda node, key: node.attrib[ANDROID + key]
    sun_path, line_path = attr(sun, "pathData"), attr(horizon, "pathData")
    # Support this two-shape sunset only; fail before writing if it changes
    # to a different kind of mark.
    sun_match = re.fullmatch(r"M([\d.]+),([\d.]+) A([\d.]+),([\d.]+) 0 0 1 ([\d.]+),([\d.]+) Z", sun_path)
    line_match = re.fullmatch(r"M([\d.]+),([\d.]+) H([\d.]+)", line_path)
    if not sun_match or not line_match:
        raise ValueError("Update this exporter for the new vector geometry.")
    left, base, rx, ry, right, end_y = map(float, sun_match.groups())
    start, line_y, finish = map(float, line_match.groups())
    if not all((math.isclose(rx, ry), math.isclose(right - left, rx * 2), math.isclose(end_y, base))):
        raise ValueError("The sun must be a semicircle.")
    cap = float(attr(horizon, "strokeWidth")) / 2
    sun_color = attr(sun, "fillColor")
    line_color = attr(horizon, "strokeColor")
    ground = attr(background.find("path"), "fillColor")
    if attr(horizon, "strokeLineCap") != "round":
        raise ValueError("The horizon must have round caps.")
    # Conservative bounds include the horizon's round caps.
    sun_extent = rx + math.hypot(left + rx - 54, base - 54)
    line_extent = max(math.hypot(x - 54, line_y - 54) for x in (start, finish)) + cap
    if max(sun_extent, line_extent) > 33:
        raise ValueError("Logo extends outside the 66dp adaptive safe circle.")

    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 72 72" width="216" height="216">
  <!-- Generated by tools/export-logo.py from the Android drawable layers. -->
  <rect width="72" height="72" rx="16" fill="{ground}"/>
  <g transform="translate(-18 -18)">
    <path fill="{sun_color}" d="{sun_path}"/>
    <path fill="none" stroke="{line_color}" stroke-width="{cap * 2:g}" stroke-linecap="round" d="{line_path}"/>
  </g>
</svg>
'''
    (ROOT / "docs/icon.svg").write_text(svg)

    def render(size, rounded=True):
        aa = 8
        scale = size * aa / 72
        at = lambda n: (n - 18) * scale
        image = Image.new("RGBA", (size * aa, size * aa))
        draw = ImageDraw.Draw(image)
        draw.rounded_rectangle((0, 0, image.width - 1, image.height - 1),
                               radius=16 * scale if rounded else 0, fill=ground)
        draw.pieslice((at(left), at(base - ry), at(right), at(base + ry)), 180, 360, fill=sun_color)
        draw.rounded_rectangle((at(start - cap), at(line_y - cap), at(finish + cap), at(line_y + cap)),
                               radius=cap * scale, fill=line_color)
        return image.resize((size, size), Image.Resampling.LANCZOS)

    meta = PngImagePlugin.PngInfo()
    meta.add_text("impeccable:prompt", ORIGIN)
    logo = render(512)
    for output in ("docs/icon.png", "fastlane/metadata/android/en-US/images/icon.png"):
        logo.save(ROOT / output, pnginfo=meta)
    # Apple applies its own mask; give it an opaque, full-bleed square.
    render(180, rounded=False).convert("RGB").save(ROOT / "docs/apple-touch-icon.png", pnginfo=meta)
    render(48).save(ROOT / "docs/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    print("Exported SVG, web/store PNGs, Apple touch icon, and 16/32/48px favicon from Android vectors.")


if __name__ == "__main__":
    main()
